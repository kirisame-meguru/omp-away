export type MessageKey = keyof typeof russian;
export function message(language: Language, english: string): string {
  return language === "ru" && Object.hasOwn(russian, english) ? russian[english as MessageKey] : english;
}

export function routingStatus(language: Language, away: boolean, delayMs: number | null): string {
  if (language === "ru") return `Все сеансы · Звонить сразу: ${away ? "вкл." : "выкл."} · Отложенный звонок: ${delayMs === null ? "выкл." : `${delayMs / 1000} с`}`;
  return `All sessions · Ring immediately: ${away ? "on" : "off"} · Fallback: ${delayMs === null ? "off" : `${delayMs / 1000}s`}`;
}

export function diagnosticCount(language: Language, count: number): string {
  return language === "ru" ? ` (повторений: ${count})` : ` (${count} occurrences)`;
}

/** Native validation remains authoritative; only recognized errors are translated. */
export function fieldValidationMessage(language: Language, field: FormField, english: string): string {
  if (language === "en") return english;
  if (field.kind === "text") {
    if (field.min !== undefined && english === `Must be at least ${field.min}`) return `Значение должно быть не меньше ${field.min}`;
    if (field.max !== undefined && english === `Must be at most ${field.max}`) return `Значение должно быть не больше ${field.max}`;
    if (field.minLength !== undefined && english === `Needs at least ${field.minLength} characters`) return `Минимальное число символов: ${field.minLength}`;
    if (field.maxLength !== undefined && english === `At most ${field.maxLength} characters`) return `Максимальное число символов: ${field.maxLength}`;
    if (field.pattern) {
      const pattern = field.pattern.length > 40 ? `${field.pattern.slice(0, 39)}…` : field.pattern;
      if (english === `Must match ${pattern}`) return `Значение должно соответствовать шаблону ${pattern}`;
    }
  }
  return message(language, english);
}
